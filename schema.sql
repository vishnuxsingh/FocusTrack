create table if not exists public.daily_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  goal_date date not null,
  title text not null check (char_length(title) between 1 and 100),
  is_mandatory boolean not null default true,
  completed boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.daily_records enable row level security;
alter table public.daily_goals enable row level security;

create policy "Users manage their own daily records"
on public.daily_records for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users manage their own daily goals"
on public.daily_goals for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create index if not exists daily_records_user_date_idx on public.daily_records(user_id, record_date);
create index if not exists daily_goals_user_date_idx on public.daily_goals(user_id, goal_date);
