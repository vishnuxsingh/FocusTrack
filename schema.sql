create table if not exists public.daily_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  record_date date not null,
  screen_minutes integer not null default 0 check (screen_minutes between 0 and 1440),
  study_minutes integer not null default 0 check (study_minutes between 0 and 1440),
  study_target_minutes integer not null default 240 check (study_target_minutes between 1 and 1440),
  screen_limit_minutes integer not null default 180 check (screen_limit_minutes between 0 and 1440),
  created_at timestamptz not null default now(),
  unique(user_id, record_date)
);
